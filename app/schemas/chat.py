"""Pydantic models for RAG Chat interactions."""

from typing import Optional, List
from pydantic import BaseModel, Field


class SourceCitation(BaseModel):
    """Source citation identifying ground-truth document chunk."""

    document_id: str = Field(..., description="ID of source document")
    filename: str = Field(..., description="Original filename")
    page: int = Field(..., description="1-indexed page number in the source PDF")
    chunk_id: str = Field(..., description="Chunk identifier within the document")
    snippet: str = Field(..., description="Relevant text excerpt extracted from chunk")
    score: Optional[float] = Field(default=None, description="Similarity score or distance metric")


class ChatRequest(BaseModel):
    """User question payload."""

    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The question to ask regarding the indexed documents",
    )
    top_k: Optional[int] = Field(
        default=None,
        ge=1,
        le=20,
        description="Optional override for number of relevant chunks to retrieve",
    )
    document_id: Optional[str] = Field(
        default=None,
        description="Optional document ID to restrict search to a single document",
    )


class ChatResponse(BaseModel):
    """Grounded answer generated by RAG pipeline along with source citations."""

    question: str
    answer: str
    sources: List[SourceCitation]
    model: str
    context_used: bool
    warning: Optional[str] = None
